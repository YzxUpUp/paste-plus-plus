import AppKit

@MainActor
final class Clipboard {
    private static let generatedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        generatedType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type")
    ]

    private let pasteboard: NSPasteboard
    private var lastChange: Int

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
    }

    var changeCount: Int { pasteboard.changeCount }

    var readDenied: Bool {
        if #available(macOS 15.4, *) {
            return pasteboard.accessBehavior == .alwaysDeny
        }
        return false
    }

    func readChange() -> String? {
        let observedChange = pasteboard.changeCount
        guard observedChange != lastChange else { return nil }
        lastChange = observedChange
        guard !readDenied,
              let types = pasteboard.types,
              types.contains(.string),
              Self.ignoredTypes.isDisjoint(with: types),
              let text = pasteboard.string(forType: .string),
              !text.isEmpty,
              pasteboard.changeCount == observedChange else { return nil }
        return text
    }

    func skipCurrentContents() {
        lastChange = pasteboard.changeCount
    }

    func put(_ text: String) -> Int? {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.generatedType)
        let writeChange = pasteboard.prepareForNewContents(with: .currentHostOnly)
        guard pasteboard.writeObjects([item]) else { return nil }
        lastChange = writeChange
        return writeChange
    }
}
